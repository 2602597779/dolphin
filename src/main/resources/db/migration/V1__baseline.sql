-- =====================================================================
-- V1 基线:11 张表全量 schema
-- 来源:2026-11-06 自 ./data H2 文件库(ddl-auto 时代多轮收敛)SCRIPT NODATA 导出,
--       与实体映射逐一对齐(Hibernate 6 / H2 方言:Instant→timestamp(6) with time zone,@Lob→clob)。
-- 说明:约束名从 Hibernate 自动名(CONSTRAINT_8 等)规范化为 pk_/uk_ 语义名;
--       identity 自增去掉存量库的 RESTART WITH(数据态),新库从 1 起;
--       H2 2.x 默认 UNIQUE 为 NULLS DISTINCT,与原库一致(系统消息 client_msg_id 可重复为 NULL)。
-- =====================================================================

-- 客户(租户)主数据:API-Key 唯一,enabled=false 即吊销
CREATE TABLE customer (
    id         VARCHAR(64)  NOT NULL,
    name       VARCHAR(128) NOT NULL,
    api_key    VARCHAR(128) NOT NULL,
    enabled    BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_customer PRIMARY KEY (id),
    CONSTRAINT uk_customer_api_key UNIQUE (api_key)
);

-- 工单台账:customer_id 为租户隔离键(NULL=内部渠道);closed_at 供 MTTR,sla_breach_at 为超时留痕
CREATE TABLE ticket (
    id            VARCHAR(64)   NOT NULL,
    raw_message   VARCHAR(8192) NOT NULL,
    status        VARCHAR(32)   NOT NULL,
    customer_id   VARCHAR(64),
    priority      VARCHAR(8),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    closed_at     TIMESTAMP(6) WITH TIME ZONE,
    sla_breach_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_ticket PRIMARY KEY (id)
);
CREATE INDEX idx_ticket_status ON ticket (status);

-- 工单对话线程:(ticket_id, client_msg_id) 唯一约束是 reply 入口幂等的数据库兜底
CREATE TABLE ticket_message (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ticket_id     VARCHAR(64)   NOT NULL,
    role          VARCHAR(8)    NOT NULL,
    content       VARCHAR(8192) NOT NULL,
    client_msg_id VARCHAR(64),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_ticket_message PRIMARY KEY (id),
    CONSTRAINT uk_message_ticket_client_msg UNIQUE (ticket_id, client_msg_id)
);
CREATE INDEX idx_message_ticket ON ticket_message (ticket_id);

-- 审批决策留痕:每单至多一条有效决策;结单清理仅置空 token,本行永久保留
CREATE TABLE approval_decision (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ticket_id  VARCHAR(64)  NOT NULL,
    approved   BOOLEAN      NOT NULL,
    approver   VARCHAR(128) NOT NULL,
    decided_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reason     VARCHAR(2048),
    token      VARCHAR(2048),
    CONSTRAINT pk_approval_decision PRIMARY KEY (id),
    CONSTRAINT uk_approval_decision_ticket UNIQUE (ticket_id)
);

-- 审批令牌一次性 nonce:纯插入、永不更新,重复主键即重放拒绝的并发兜底
CREATE TABLE approval_token_nonce (
    nonce      VARCHAR(64) NOT NULL,
    expires_at BIGINT      NOT NULL,
    CONSTRAINT pk_approval_token_nonce PRIMARY KEY (nonce)
);

-- 写操作幂等:idem_key = ticketId|action|target,重启后去重依然生效
CREATE TABLE action_idempotency (
    idem_key   VARCHAR(512) NOT NULL,
    action     VARCHAR(64)  NOT NULL,
    ticket_id  VARCHAR(64)  NOT NULL,
    result     CLOB,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_action_idempotency PRIMARY KEY (idem_key)
);
CREATE INDEX idx_idempotency_ticket ON action_idempotency (ticket_id);

-- 图 checkpoint:按工单一行,审批中断后跨进程 resume(HITL 持久化关键)
CREATE TABLE graph_checkpoint (
    ticket_id   VARCHAR(64) NOT NULL,
    node_id     VARCHAR(64) NOT NULL,
    next_node   VARCHAR(64) NOT NULL,
    config_json CLOB,
    state_json  CLOB        NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_graph_checkpoint PRIMARY KEY (ticket_id)
);

-- 转人工任务池:每单至多一条,专员认领/完结
CREATE TABLE human_task (
    ticket_id  VARCHAR(64)  NOT NULL,
    reason     VARCHAR(512) NOT NULL,
    detail     CLOB,
    status     VARCHAR(32)  NOT NULL,
    owner      VARCHAR(128) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_human_task PRIMARY KEY (ticket_id)
);

-- 统一审计留痕:工单链路 session_id=工单号,告警链路=指纹;id 单调,时间线排序键
CREATE TABLE audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    session_id VARCHAR(64)  NOT NULL,
    action     VARCHAR(128) NOT NULL,
    detail     CLOB,
    at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (id)
);

-- 已受理告警事件:fingerprint 主键,重复指纹 upsert 覆盖为最新
CREATE TABLE alert_event (
    fingerprint  VARCHAR(64)   NOT NULL,
    status       VARCHAR(16)   NOT NULL,
    alert_name   VARCHAR(128)  NOT NULL,
    severity     VARCHAR(32)   NOT NULL,
    summary      VARCHAR(2048) NOT NULL,
    labels_json  CLOB,
    starts_at    VARCHAR(64)   NOT NULL,
    received_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_alert_event PRIMARY KEY (fingerprint)
);

-- 告警诊断记录:异步 Agent 诊断 + 通知结果台账
CREATE TABLE alert_diagnosis (
    seq           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fingerprint   VARCHAR(64)  NOT NULL,
    alert_name    VARCHAR(128) NOT NULL,
    task_name     VARCHAR(128) NOT NULL,
    outcome       VARCHAR(32)  NOT NULL,
    report        CLOB,
    proposal      CLOB,
    notified      BOOLEAN      NOT NULL,
    notify_detail VARCHAR(1024) NOT NULL,
    at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_alert_diagnosis PRIMARY KEY (seq)
);
CREATE INDEX idx_alert_diagnosis_fp ON alert_diagnosis (fingerprint);
